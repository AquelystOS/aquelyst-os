def get_seeds_for_filter(business_type=None, state=None, max_count=50):
    """
    Filter the seed list by business type and/or state.
    Returns list compatible with discovery format.
    """
    filtered = SEED_BUSINESSES

    if state:
        state_upper = state.upper()
        filtered = [b for b in filtered if b['state'] == state_upper]

    if business_type:
        bt_lower = business_type.lower()
        filtered = [b for b in filtered if bt_lower in b['type'].lower()]

    # Convert to discovery candidate format
    results = []
    for b in filtered[:max_count]:
        website = b['website']
        if not website.startswith(('http://', 'https://')):
            website = 'https://' + website
        results.append({
            'url': website,
            'title': b['name'],
            'snippet': f"{b['type']} in {b['city']}, {b['state']}",
            '_seed_city': b['city'],
            '_seed_state': b['state'],
        })

    return results


